def write_report(summary: dict, systems: dict[str, EvalResult], out_dir: Path,
                 train_meta: dict | None) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    md = results_markdown(summary, train_meta)
    figures: list[str] = []
    try:
        import matplotlib

        matplotlib.use("Agg")
        plot_systems(summary, out_dir / "fig_systems.png")
        figures.append("fig_systems.png")
        plot_recall_at_k(summary, systems, out_dir / "fig_recall_at_k.png")
        figures.append("fig_recall_at_k.png")
        plot_bm25_grid(summary["bm25_grid"], out_dir / "fig_bm25_grid.png")
        figures.append("fig_bm25_grid.png")
        if summary.get("ft_grid"):
            plot_ft_grid(summary["ft_grid"], out_dir / "fig_ft_grid.png")
            figures.append("fig_ft_grid.png")
        rr = (summary.get("reranker") or {}).get("training")
        if plot_training(train_meta, rr, out_dir / "fig_training.png"):
            figures.append("fig_training.png")
    except ImportError:
        log.warning("matplotlib not installed: figures skipped")
    if figures:
        md += "\n## Figures\n\n" + "\n".join(f"![{f}]({f})" for f in figures) + "\n"
    (out_dir / "results.md").write_text(md, encoding="utf-8")
    summary = {**summary, "figures": figures}
    if summary.get("reranker") and summary["reranker"].get("training"):
        tr = summary["reranker"]["training"]
        summary["reranker"] = {**summary["reranker"],
                               "training": {**tr, "loss_curve": [[h["step"], h["loss"]]
                                                                 for h in tr.get("log_history", [])]}}
        summary["reranker"]["training"].pop("log_history", None)
    (out_dir / "results.json").write_text(json.dumps(summary, ensure_ascii=False, indent=1),
                                          encoding="utf-8")
    log.info("final report written to %s", out_dir)
