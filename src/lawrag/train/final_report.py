def results_markdown(summary: dict, train_meta: dict | None) -> str:
    S, data = summary["systems"], summary["data"]
    L = ["# Final experiment — generated results", "",
         f"_Generated by `lawrag final-experiment` on {time.strftime('%Y-%m-%d %H:%M')}. "
         "Do not edit by hand; re-run the command._", ""]

    # --- data
    L += ["## 1. Data split (by article)", "",
          "| split | used for | pairs | articles | heading | xref | xlang | definition |",
          "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    uses = {"train": "training every model", "validation": "every tuning / selection decision",
            "test": "final numbers only (touched once)"}
    for split in ("train", "validation", "test"):
        d = data[split]
        L.append(f"| {split} | {uses[split]} | {d['pairs']:,} | {d['articles']:,} | "
                 + " | ".join(f"{d['kinds'].get(k, 0):,}"
                              for k in ("heading", "xref", "xlang", "definition")) + " |")
    L += ["", f"Corpus: {data['chunks']:,} chunks, ranked in full for every test query. "
          f"Articles shared between any two splits: {data['shared_articles']}.", ""]

    # --- the unified table
    L += ["## 2. Unified results (test split)", "",
          "Same 1 test split, same corpus, same metrics for every system; 95% bootstrap "
          "intervals over queries (2,000 resamples). Rerankers reorder the top "
          f"{(summary.get('reranker') or {}).get('depth', 20)} of the first stage "
          f"(`{summary.get('stage1')}`).", "",
          "| # | system | family | learns from | tuning | Recall@1 | Recall@10 | MRR@10 |",
          "| ---: | --- | --- | --- | --- | --- | --- | --- |"]
    for i, n in enumerate(_ordered(summary), 1):
        s = S[n]
        o = s["overall"]
        bold = "**" if n == summary["best_system"] else ""
        L.append(f"| {i} | {bold}{s['label']}{bold} | {s['family']} | {s['learned_from']} | "
                 f"{s['tuning']} | {_ci(o['recall@1'])} | {_ci(o['recall@10'])} | "
                 f"{bold}{_ci(o['mrr@10'])}{bold} |")

    L += ["", "### Each change, measured against what it changes", "",
          "Paired on the same test queries; an interval that excludes 0 is a "
          "significant difference.", "",
          "| change | system − baseline | Δ MRR@10 | Δ Recall@1 | Δ Recall@10 | better | worse |",
          "| --- | --- | --- | --- | --- | ---: | ---: |"]
    for st in summary["steps"]:
        L.append(f"| {st['label']} | `{st['system']}` − `{st['baseline']}` | {_d(st['mrr@10'])} | "
                 f"{_d(st['recall@1'])} | {_d(st['recall@10'])} | {st['better']} | {st['worse']} |")

    L += ["", "### By query kind and language (MRR@10)", "",
          "| system | heading | xlang | xref | KK queries | RU queries |",
          "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for n in _ordered(summary):
        s = S[n]
        vals = {k["kind"]: k["mrr@10"] for k in s["per_kind"] + s["per_lang"]}
        L.append(f"| {s['label']} | " + " | ".join(
            f"{vals.get(k, 0):.3f}" for k in ("heading", "xlang", "xref", "kk", "ru")) + " |")

    # --- tuning
    L += ["", "## 3. Hyper-parameter tuning (validation split)", ""]
    g = summary["bm25_grid"]
    L += ["### 3.1 BM25 — exhaustive grid", "",
          f"Search space ({g['n_trials']} points, `ParameterGrid`), scored on all "
          f"{g['default']['n']:,} validation queries against the full corpus, selected by "
          "MRR@10 (ties: Recall@10):", "",
          "| parameter | values |", "| --- | --- |",
          f"| stem length (`prefix`, 0 = whole word) | {g['space']['prefix']} |",
          f"| k1 (term-frequency saturation) | {g['space']['k1']} |",
          f"| b (length normalisation) | {g['space']['b']} |", "",
          "| configuration | prefix | k1 | b | val Recall@1 | val Recall@10 | val MRR@10 |",
          "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for name, t in (("midterm default", g["default"]), ("**best**", g["best"])):
        L.append(f"| {name} | {t['prefix']} | {t['k1']} | {t['b']} | {t['recall@1']:.3f} | "
                 f"{t['recall@10']:.3f} | {t['mrr@10']:.3f} |")
    L += ["", "Best MRR@10 per stem length:", "", "| prefix | best k1 | best b | val MRR@10 |",
          "| ---: | ---: | ---: | ---: |"]
    for prefix in g["space"]["prefix"]:
        t = max((t for t in g["trials"] if t["prefix"] == prefix), key=lambda t: t["mrr@10"])
        L.append(f"| {prefix or 'whole word'} | {t['k1']} | {t['b']} | {t['mrr@10']:.3f} |")

    ft = summary.get("ft_grid")
    if ft:
        L += ["", "### 3.2 bge-m3 fine-tuning — exhaustive grid (low-fidelity trials)", "",
              f"Each trial fine-tunes stock bge-m3 on the same {ft['trial_pairs']:,} training "
              f"pairs and is scored on a fixed validation pool of {ft['pool_chunks']:,} chunks "
              "(every chunk of the validation articles + the top 30 per validation query under "
              "stock bge-m3 and BM25 + 5,000 random chunks). Everything else as in § 4.", "",
              "| learning rate \\ trainable top layers | "
              + " | ".join(str(v) for v in ft["space"]["train_layers"]) + " |",
              "| --- |" + " ---: |" * len(ft["space"]["train_layers"])]
        by = {(t["learning_rate"], t["train_layers"]): t for t in ft["trials"]}
        for lr in ft["space"]["learning_rate"]:
            cells = []
            for layers in ft["space"]["train_layers"]:
                t = by.get((lr, layers))
                mark = "**" if t is ft["best"] or t == ft["best"] else ""
                cells.append(f"{mark}{t['mrr@10']:.3f}{mark}" if t else "—")
            L.append(f"| {lr:g} | " + " | ".join(cells) + " |")
        L += ["", f"Cells: validation-pool MRR@10. Selected: learning rate "
              f"**{ft['best']['learning_rate']:g}**, top **{ft['best']['train_layers']}** layers "
              f"(Recall@10 {ft['best']['recall@10']:.3f})."]
        if ft.get("reference"):
            ref = ft["reference"]
            L += ["", "Reference points on the same pool: stock bge-m3 (zero-shot) MRR@10 "
                  f"{ref['zero-shot']['mrr@10']:.3f}" if "zero-shot" in ref else ""]
            if "midterm" in ref:
                L[-1] += (f"; the midterm model {ref['midterm']['mrr@10']:.3f} — **not comparable**: "
                          "it was trained on all of the midterm's train articles, which include "
                          "this validation split, so it has seen these answers. It is shown as a "
                          "leak check only; on the untouched test split it is row 4 of § 2")
            L[-1] += "."

    h = summary.get("hybrid")
    if h:
        se = h["search"]
        L += ["", "### 3.3 Learned hybrid — randomized search and grid search", "",
              f"Candidates: union of the top {h['candidates_per_list']} of BM25 (tuned) and "
              f"bge-m3 (fine-tuned) — {h['val_rows']:,} validation rows, "
              f"{h['val_positive_rate']:.1%} positive; the right article is among the "
              f"candidates for {h['val_recall_of_candidates']:.1%} of validation and "
              f"{h['test_recall_of_candidates']:.1%} of test queries. Model selection by "
              "5-fold GroupKFold (grouped by article) on MRR@10.", "",
              "| model | search | space | default CV MRR@10 | best CV MRR@10 | best parameters |",
              "| --- | --- | --- | ---: | ---: | --- |"]
        for kind, label in (("logreg", "logistic regression"), ("hgb", "gradient boosting")):
            s = se[kind]
            space = "; ".join(f"{k} ∈ {v}" for k, v in s["space"].items())
            params = ", ".join(f"{k}={_fmt(v)}" for k, v in s["best"]["params"].items())
            L.append(f"| {label} | {s['search']} ({len(s['trials']) - (1 if kind == 'hgb' else 0)}"
                     f" points) | {space} | {s['default']['cv_mrr@10']:.3f} | "
                     f"{s['best']['cv_mrr@10']:.3f} | {params} |")

    # --- classical ML before / after
    L += ["", "## 4. Classical ML: before and after tuning (test split)", "",
          "| model | before tuning: Recall@1 / Recall@10 / MRR@10 | after tuning | Δ MRR@10 |",
          "| --- | --- | --- | --- |"]
    for before, after, label in (("bm25-default", "bm25-tuned", "BM25"),
                                 ("hybrid-logreg-default", "hybrid-logreg-tuned",
                                  "hybrid: logistic regression"),
                                 ("hybrid-hgb-default", "hybrid-hgb-tuned",
                                  "hybrid: gradient boosting")):
        if before in S and after in S:
            b, a = S[before]["overall"], S[after]["overall"]
            step = next((st for st in summary["steps"]
                         if st["system"] == after and st["baseline"] == before), None)
            L.append(f"| {label} | {b['recall@1'][0]:.3f} / {b['recall@10'][0]:.3f} / "
                     f"{b['mrr@10'][0]:.3f} | {a['recall@1'][0]:.3f} / {a['recall@10'][0]:.3f} / "
                     f"{a['mrr@10'][0]:.3f} | {_d(step['mrr@10']) if step else '—'} |")
    if h and h.get("importance"):
        L += ["", "Permutation importance of the hybrid's features (drop in validation average "
              "precision; tuned models) and the logistic-regression coefficients "
              "(standardised features):", "",
              "| feature | gradient boosting | logistic regression | LR coefficient |",
              "| --- | ---: | ---: | ---: |"]
        coef = h.get("logreg_coefficients", {})
        for f in h["features"]:
            L.append(f"| `{f}` | {h['importance'].get('hgb', {}).get(f, 0):.4f} | "
                     f"{h['importance'].get('logreg', {}).get(f, 0):.4f} | {coef.get(f, 0):+.3f} |")

    # --- fine-tuning configuration
    if train_meta:
        s = train_meta["settings"]
        L += ["", "## 5. Fine-tuning configuration — bge-m3 bi-encoder (`dense-final`)", "",
              "| parameter | value |", "| --- | --- |"]
        rows = [("base model", f"{Path(str(train_meta['base'])).name} (XLM-RoBERTa-large, 568M)"),
                ("training pairs", f"{train_meta['pairs']:,} (train split)"),
                ("epochs", s["epochs"]), ("batch size (in-batch negatives)", s["batch_size"]),
                ("mini-batch (GradCache)", s["mini_batch_size"]),
                ("optimizer", f"{s.get('optim', 'adamw_torch')} (AdamW), weight decay "
                              f"{s.get('weight_decay', 0.0)}"),
                ("learning rate", f"{s['learning_rate']:g} (selected by § 3.2)"),
                ("schedule", f"{s.get('lr_scheduler', 'linear')}, {s.get('warmup_ratio', 0.1):.0%} "
                             "linear warm-up"),
                ("loss", train_meta.get("loss", "CachedMultipleNegativesRankingLoss")),
                ("negatives", f"31 in-batch + 1 hard negative per pair (top-"
                              f"{s['hard_negative_top_k']} wrong article under the base model)"),
                ("max sequence length", s["max_seq_length"]),
                ("trainable layers", f"top {s['train_layers']} of 24 (selected by § 3.2)"),
                ("trainable / frozen parameters",
                 f"{train_meta['trainable_parameters'] / 1e6:.1f}M / "
                 f"{train_meta['frozen_parameters'] / 1e6:.1f}M"),
                ("precision", "fp16 mixed precision, gradient checkpointing"),
                ("held-out articles (never positive nor negative)", train_meta["held_out_articles"]),
                ("seed", s["seed"]), ("training time", f"{train_meta['train_seconds'] / 60:.0f} min")]
        L += [f"| {k} | {v} |" for k, v in rows]

    # --- QLoRA configuration
    rr = (summary.get("reranker") or {}).get("training")
    if rr:
        s = rr["settings"]
        L += ["", "## 6. LoRA configuration — Qwen3-0.6B reranker (`rerank-qwen-lora`)", "",
              "| parameter | value |", "| --- | --- |"]
        eff = s["grad_accum"] * s["group_size"]
        rows = [("base model", f"{s['base']} (decoder LLM, 28 layers, frozen)"),
                ("quantisation", (f"QLoRA: 4-bit {s['quant_type'].upper()}, double quantisation "
                                  f"{'on' if s['double_quant'] else 'off'}, compute {s['compute_dtype']}")
                 if s["load_in_4bit"] else
                 "none: frozen base in bf16, adapters in fp32 (4-bit QLoRA crashed the GPU "
                 "driver on this machine; see llm_rerank.py)"),
                ("LoRA rank r", s["lora_r"]), ("LoRA alpha", f"{s['lora_alpha']} "
                                                              f"(scale alpha/r = {s['lora_alpha'] / s['lora_r']:g})"),
                ("LoRA dropout", s["lora_dropout"]),
                ("target modules", ", ".join(f"`{m}`" for m in s["target_modules"])),
                ("trainable parameters", f"{rr['trainable_parameters']:,} of "
                                         f"{rr['total_parameters']:,} "
                                         f"({100 * rr['trainable_parameters'] / rr['total_parameters']:.2f}%)"),
                ("optimizer", f"AdamW, weight decay {s['weight_decay']}, grad-norm clip "
                              f"{s['max_grad_norm']}"),
                ("learning rate", f"{s['learning_rate']:g}, {s['lr_scheduler']} schedule, "
                                  f"{s['warmup_ratio']:.0%} warm-up"),
                ("epochs", s["epochs"]),
                ("batch", f"{s['grad_accum']} groups x {s['group_size']} documents = {eff} "
                          "sequences per optimiser step"),
                ("training data", f"{rr['groups']:,} groups (1 positive + {s['group_size'] - 1} "
                                  f"negatives: {s['hard_negatives']} hardest + "
                                  f"{s['group_size'] - 1 - s['hard_negatives']} sampled from the "
                                  f"fine-tuned bi-encoder's top {s['negative_pool']})"),
                ("loss", s["loss"]), ("score", "logit(\"yes\") − logit(\"no\") at the answer slot"),
                ("max length", f"{s['max_len']} tokens (query ≤ {s['max_query_tokens']})"),
                ("optimiser steps", rr["optimizer_steps"]),
                ("peak VRAM", f"{rr['peak_vram_gb']} GB" if rr.get("peak_vram_gb") else "—"),
                ("seed", s["seed"]), ("training time", f"{rr['train_seconds'] / 60:.0f} min")]
        L += [f"| {k} | {v} |" for k, v in rows]

    # --- shortcut and errors
    ns = summary.get("number_shortcut")
    if ns:
        L += ["", "## 7. Shortcut check — leftover article numbers in `xref` queries", "",
              "| system | MRR@10, query names another article | MRR@10, no number | misses lured "
              "to the named article |", "| --- | --- | --- | ---: |"]
        for n, m in ns.items():
            L.append(f"| {S[n]['label']} | {m['with_number']['mrr@10']:.3f} "
                     f"(n={m['with_number']['n']}) | {m['without_number']['mrr@10']:.3f} "
                     f"(n={m['without_number']['n']}) | {m['lured_share_of_misses']:.0%} |")
    for n, e in (summary.get("errors") or {}).items():
        L += ["", f"## Error analysis — {S[n]['label']}", "",
              f"{e['misses_at_1']} of {e['queries']} test queries miss rank 1 (median rank of a "
              f"miss: {e['median_rank_of_misses']:.0f}).", "",
              "| where the top-1 landed | queries | share |", "| --- | ---: | ---: |"]
        for cat, k in e["categories"].items():
            L.append(f"| {cat} | {k} | {k / max(1, e['misses_at_1']):.0%} |")

    # --- environment
    env = summary["environment"]
    L += ["", "## Reproducibility", "",
          f"* seed **{env['seed']}** everywhere (pair shuffling, hard-negative sampling, "
          "trainer, bootstrap, hybrid CV and search); validation hash seed 29; test split "
          "unchanged from the midterm (hash seed 13);",
          f"* git commit `{env['git_commit']}`{' (with uncommitted changes)' if env['git_dirty'] else ''};",
          f"* Python {env['python']} on {env['platform']}"
          + (f"; GPU {env['gpu']['name']} ({env['gpu']['vram_gb']} GB, CUDA {env['gpu']['cuda']})"
             if env.get("gpu") else "") + ";", "",
          "| library | version |", "| --- | --- |"]
    L += [f"| {k} | {v or '—'} |" for k, v in env["libraries"].items()]
    return "\n".join(L) + "\n"


def _fmt(v) -> str:
    return f"{v:.3g}" if isinstance(v, float) else str(v)


