def plot_systems(summary: dict, path: Path) -> None:
    """MRR@10 per system on test, with 95% intervals; colour = family,
    hatching = not adapted to this task (default parameters / zero-shot)."""
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch

    names = _ordered(summary)[::-1]
    S = summary["systems"]
    fig, ax = plt.subplots(figsize=(8.6, 0.42 * len(names) + 2.0), facecolor=SURFACE)
    _style(ax)
    ax.grid(axis="y", visible=False)
    for i, n in enumerate(names):
        v, lo, hi = S[n]["overall"]["mrr@10"]
        color = FAMILY_COLORS[S[n]["family"]]
        ax.barh(i, v, height=0.68, color=color, edgecolor=SURFACE, linewidth=2,
                hatch="////" if n in UNTUNED else None)
        ax.errorbar(v, i, xerr=[[v - lo], [hi - v]], color=INK_2, linewidth=1, capsize=2.5)
        ax.text(hi + 0.008, i, f"{v:.3f}", va="center", fontsize=8, color=INK)
    ax.set_yticks(range(len(names)), [S[n]["label"] for n in names], fontsize=8.5, color=INK)
    ax.set_xlabel("MRR@10 on the test split (95% bootstrap interval)", color=INK_2, fontsize=9)
    ax.set_xlim(0, min(1.0, max(S[n]["overall"]["mrr@10"][2] for n in names) + 0.09))
    handles = [Patch(facecolor=FAMILY_COLORS[f], label=FAMILY_LABELS[f])
               for f in FAMILY_COLORS if any(S[n]["family"] == f for n in names)]
    handles.append(Patch(facecolor=SURFACE, edgecolor=INK_2, hatch="////",
                         label="not adapted (defaults / zero-shot)"))
    # Below the plot, so it never covers a bar or its value label.
    fig.legend(handles=handles, frameon=False, fontsize=8, loc="lower center", ncol=3,
               labelcolor=INK)
    fig.tight_layout(rect=(0, 0.09, 1, 1))
    fig.savefig(path, dpi=160, facecolor=SURFACE)
    plt.close(fig)


def _heatmap(ax, values: np.ndarray, xlabels, ylabels, best: tuple[int, int] | None) -> None:
    from matplotlib.colors import LinearSegmentedColormap

    cmap = LinearSegmentedColormap.from_list("blues", BLUES)
    lo, hi = float(np.nanmin(values)), float(np.nanmax(values))
    ax.imshow(values, cmap=cmap, vmin=lo, vmax=hi if hi > lo else lo + 1e-6, aspect="auto")
    for (r, c), v in np.ndenumerate(values):
        dark = (v - lo) / max(hi - lo, 1e-9) > 0.55
        ax.text(c, r, f"{v:.3f}", ha="center", va="center", fontsize=7.5,
                color=SURFACE if dark else INK,
                fontweight="bold" if best == (r, c) else "normal")
    if best:
        ax.add_patch(__import__("matplotlib.patches", fromlist=["Rectangle"]).Rectangle(
            (best[1] - 0.5, best[0] - 0.5), 1, 1, fill=False, edgecolor=INK, linewidth=1.6))
    ax.set_xticks(range(len(xlabels)), xlabels, fontsize=8, color=INK_2)
    ax.set_yticks(range(len(ylabels)), ylabels, fontsize=8, color=INK_2)
    for side in ax.spines.values():
        side.set_visible(False)


def plot_bm25_grid(grid: dict, path: Path) -> None:
    import matplotlib.pyplot as plt

    best = grid["best"]
    k1s, bs = grid["space"]["k1"], grid["space"]["b"]
    vals = np.full((len(k1s), len(bs)), np.nan)
    for t in grid["trials"]:
        if t["prefix"] == best["prefix"]:
            vals[k1s.index(t["k1"]), bs.index(t["b"])] = t["mrr@10"]
    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(9.6, 3.6), facecolor=SURFACE,
                                  gridspec_kw={"width_ratios": [1.35, 1]})
    _heatmap(ax, vals, [str(b) for b in bs], [str(k) for k in k1s],
             (k1s.index(best["k1"]), bs.index(best["b"])))
    ax.set_xlabel("b (length normalisation)", color=INK_2, fontsize=9)
    ax.set_ylabel("k1 (tf saturation)", color=INK_2, fontsize=9)
    ax.set_title(f"validation MRR@10, stem length {best['prefix'] or 'whole word'}",
                 fontsize=9, color=INK, loc="left")
    _style(ax2)
    ax2.grid(axis="x", visible=False)
    prefixes = grid["space"]["prefix"]
    tops = [max(t["mrr@10"] for t in grid["trials"] if t["prefix"] == p) for p in prefixes]
    bars = ax2.bar(range(len(prefixes)), tops, width=0.7, color=FAMILY_COLORS["lexical"],
                   edgecolor=SURFACE, linewidth=2)
    for b_, v in zip(bars, tops):
        ax2.text(b_.get_x() + b_.get_width() / 2, v + 0.004, f"{v:.3f}", ha="center",
                 fontsize=7.5, color=INK)
    ax2.axhline(grid["default"]["mrr@10"], color=INK_2, linewidth=1, linestyle="--")
    ax2.set_xticks(range(len(prefixes)), [str(p) if p else "word" for p in prefixes])
    ax2.set_xlabel("stem length (characters kept)", color=INK_2, fontsize=9)
    ax2.set_title("best MRR@10 per stem length (dashed: midterm default)", fontsize=9,
                  color=INK, loc="left")
    lo = min(tops + [grid["default"]["mrr@10"]])
    ax2.set_ylim(max(0, lo - 0.05), max(tops) + 0.03)
    fig.tight_layout()
