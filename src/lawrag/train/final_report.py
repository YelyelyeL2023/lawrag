# One colour per family, categorical slots 1-4 of the validated reference
# palette in their fixed order (adjacent-pair CVD-safe; the two light hues
# sit below 3:1 on the surface, so every bar carries a visible value label).
FAMILY_COLORS = {"dense": "#2a78d6", "reranker": "#eb6834", "lexical": "#1baf7a",
                 "hybrid": "#eda100"}
FAMILY_LABELS = {"lexical": "lexical (BM25)", "dense": "dense bi-encoder (bge-m3)",
                 "hybrid": "classical ML hybrid", "reranker": "second-stage reranker"}
# Sequential blue ramp (steps 100 -> 650) for the grid heatmaps.
BLUES = ["#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#184f95", "#104281"]

ORDER = ["bm25-default", "bm25-tuned", "dense-zeroshot", "dense-midterm", "dense-final",
         "hybrid-logreg-default", "hybrid-logreg-tuned", "hybrid-hgb-default",
         "hybrid-hgb-tuned", "rerank-bge", "rerank-qwen-zeroshot", "rerank-qwen-lora"]
UNTUNED = {"bm25-default", "dense-zeroshot", "hybrid-logreg-default", "hybrid-hgb-default",
           "rerank-bge", "rerank-qwen-zeroshot"}


def _ci(v: list[float]) -> str:
    return f"{v[0]:.3f} [{v[1]:.3f}, {v[2]:.3f}]"


def _d(v: list[float]) -> str:
    return f"{v[0]:+.3f} [{v[1]:+.3f}, {v[2]:+.3f}]"


def _ordered(summary: dict) -> list[str]:
    return [n for n in ORDER if n in summary["systems"]]


