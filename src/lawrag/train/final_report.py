def plot_training(ft_meta: dict | None, rr: dict | None, path: Path) -> bool:
    import matplotlib.pyplot as plt

    panels = []
    h = [x for x in (ft_meta or {}).get("log_history", []) if "loss" in x]
    if len(h) >= 2:
        panels.append(("bge-m3 fine-tuning — MNRL loss", "epoch",
                       [x["epoch"] for x in h], [x["loss"] for x in h], FAMILY_COLORS["dense"]))
    h = (rr or {}).get("log_history", [])
    if len(h) >= 2:
        panels.append(("Qwen3-0.6B LoRA — listwise loss", "optimiser step",
                       [x["step"] for x in h], [x["loss"] for x in h], FAMILY_COLORS["reranker"]))
        panels.append(("Qwen3-0.6B LoRA — positive ranked 1st of 8", "optimiser step",
                       [x["step"] for x in h], [x["group_acc"] for x in h],
                       FAMILY_COLORS["reranker"]))
    if not panels:
        return False
    fig, axes = plt.subplots(1, len(panels), figsize=(3.6 * len(panels), 3.0), facecolor=SURFACE,
                             squeeze=False)
    for ax, (title, xlabel, x, y, color) in zip(axes[0], panels):
        _style(ax)
        ax.plot(x, y, color=color, linewidth=1, alpha=0.35)
        if len(y) >= 5:
            sm = np.convolve(y, np.ones(5) / 5, mode="valid")
            ax.plot(x[2:-2], sm, color=color, linewidth=2)
        ax.set_title(title, fontsize=9, color=INK, loc="left")
        ax.set_xlabel(xlabel, color=INK_2, fontsize=9)
    fig.tight_layout()
    fig.savefig(path, dpi=160, facecolor=SURFACE)
    plt.close(fig)
    return True


def plot_recall_at_k(summary: dict, systems: dict[str, EvalResult], path: Path,
                     max_k: int = 20) -> None:
    import matplotlib.pyplot as plt

    picks = [n for n in ("bm25-tuned", "dense-zeroshot", "dense-final", summary.get("stage1"),
                         "rerank-qwen-lora") if n and n in systems]
    picks = list(dict.fromkeys(picks))
    S = summary["systems"]
    ks = np.arange(1, max_k + 1)
    fig, ax = plt.subplots(figsize=(6.4, 3.6), facecolor=SURFACE)
    _style(ax)
    ends = []
    for n in picks:
        r = np.array([q["rank"] for q in systems[n].queries])
        curve = [_hit(r, k).mean() for k in ks]
        ax.plot(ks, curve, color=FAMILY_COLORS[S[n]["family"]], linewidth=2,
                linestyle="--" if n in UNTUNED else "-", label=S[n]["label"])
        ends.append((curve[-1], S[n]["label"]))
    ax.set_xlabel("k", color=INK_2, fontsize=9)
    ax.set_ylabel("Recall@k (test)", color=INK_2, fontsize=9)
    ax.set_xticks([1, 5, 10, 15, 20])
    ax.set_ylim(0, 1.0)
    ax.legend(frameon=False, fontsize=8, loc="lower right", labelcolor=INK)
    fig.tight_layout()
    fig.savefig(path, dpi=160, facecolor=SURFACE)
    plt.close(fig)


